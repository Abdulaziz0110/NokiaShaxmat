    private static final Random RND = new Random();

    /**
     * Returns a book move (UCI string) that follows the game so far, or null.
     * @param played UCI moves played from the start position, separated by single spaces
     */
    public static String probe(String played) {
        int count = 0;
        String[] cand = new String[LINES.length];
        int plen = played.length();
        for (int i = 0; i < LINES.length; i++) {
            String l = LINES[i];
            if (plen == 0) {
                cand[count++] = l.substring(0, 4);
                continue;
            }
            if (l.length() > plen + 4 && l.startsWith(played) && l.charAt(plen) == ' ') {
                int s = plen + 1;
                int e = l.indexOf(' ', s);
                if (e < 0) e = l.length();
                cand[count++] = l.substring(s, e);
            }
        }
        if (count == 0) return null;
        return cand[RND.nextInt(count)];
    }

    /** For tests: all lines. */
    public static int lineCount() { return LINES.length; }
    public static String line(int i) { return LINES[i]; }
